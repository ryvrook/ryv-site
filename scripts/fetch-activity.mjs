// Regenerates data/activity.ts and prints current language share.
// Needs an authenticated gh CLI. Run: bun run activity
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

// Slug -> repo. Keep in sync with data/projects.ts.
const repos = {
  'flock-directories': 'ryvrook/flockdirectories',
  'friday-bot': 'ryvrook/friday-bot',
  dotfiles: 'ryvrook/dotfiles',
  'nef-list': 'ryvrook/nef-list',
  'endpoint-game': 'ryvrook/endpoint-game',
  'enterprise-vectordns': 'ryvrook/enterprise-vectordns',
  roadrunner: 'ryvrook/roadrunner',
  treecreeper: 'ryvrook/treecreeper',
  qwuickswap: 'ryvrook/qwuickswap',
  'qwuick-bot': 'ryvrook/qwuick-bot',
  'this-site': 'ryvrook/ryv-site',
  ternix: 'ryvrook/ternix',
  wrensmith: 'ryvrook/wrensmith',
  askfriday: 'ryvrook/AskFriday',
  swallowtail: 'ryvrook/Swallowtail',
  corviddata: 'ryvrook/corviddata',
  randomizr: 'ryvrook/Randomizr',
  agenttailor: 'ryvrook/agenttailor',
  'vdns-tui': 'Vector-DNS/vdns-tui',
  vectordns: 'ryvrook/VectorDNS',
  'vectordns-server': 'ryvrook/vectordns-server',
  'vdns-cli': 'Vector-DNS/vdns-cli',
  'lotus-mail': 'ryvrook/lotus-mail',
  'vectordns-admin': 'ryvrook/vectordns-admin',
  webhaptics: 'ryvrook/WebHapticsTest',
};

function fetchWeeks(repo) {
  // GitHub computes stats lazily, first calls can 202/empty.
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const out = execFileSync(
        'gh',
        ['api', `repos/${repo}/stats/commit_activity`, '--jq', '[.[].total]'],
        { encoding: 'utf8' },
      ).trim();
      if (out) return JSON.parse(out);
    } catch {}
    execFileSync('sleep', ['3']);
  }
  console.error(`no stats for ${repo}, writing zeros`);
  return Array(52).fill(0);
}

const entries = {};
for (const [slug, repo] of Object.entries(repos)) {
  entries[slug] = fetchWeeks(repo);
  console.log(`${slug}: ${entries[slug].reduce((a, b) => a + b, 0)} commits/52w`);
}

const generatedAt = new Date().toISOString().slice(0, 10);
const file = `// Generated by scripts/fetch-activity.mjs on ${generatedAt}. Do not edit by hand.
// 52 weekly commit totals per project slug, oldest week first.

export const activityGeneratedAt = '${generatedAt}';

export const activity: Record<string, number[]> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL('../data/activity.ts', import.meta.url), file);
console.log('wrote data/activity.ts');

const langBytes = {};
for (const repo of Object.values(repos)) {
  try {
    const out = execFileSync('gh', ['api', `repos/${repo}/languages`], {
      encoding: 'utf8',
    });
    for (const [lang, bytes] of Object.entries(JSON.parse(out))) {
      langBytes[lang] = (langBytes[lang] || 0) + bytes;
    }
  } catch {
    console.error(`no languages for ${repo}`);
  }
}
const totalBytes = Object.values(langBytes).reduce((a, b) => a + b, 0);
const top = Object.entries(langBytes)
  .sort((a, b) => b[1] - a[1])
  .filter(([, bytes]) => bytes / totalBytes >= 0.01)
  .slice(0, 6)
  .map(([name, bytes]) => ({
    name,
    percent: Math.round((bytes / totalBytes) * 1000) / 10,
  }));

console.log('\ncurrent GitHub language share (update data/languages.ts by hand):');
for (const { name, percent } of top) {
  console.log(`  { name: '${name}', percent: ${percent} },`);
}
